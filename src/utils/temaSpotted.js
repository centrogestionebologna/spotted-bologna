function normalizzaTesto(testo) {
  return String(testo || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[\u200B-\u200D\uFEFF]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function escapeRegExp(testo) {
  return testo.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const LOCALITA = NOMI_LOCALITA.map((nome) => ({
  nome,
  normalizzata: normalizzaTesto(nome)
})).sort(
  (prima, seconda) =>
    seconda.normalizzata.length - prima.normalizzata.length
);

function trovaLocalita(testoNormalizzato) {
  const trovate = [];

  LOCALITA.forEach((localita) => {
    const regex = new RegExp(
      `\\b${escapeRegExp(localita.normalizzata)}\\b`,
      "i"
    );
    const match = regex.exec(testoNormalizzato);

    if (match) {
      trovate.push({
        ...localita,
        indice: match.index
      });
    }
  });

  trovate.sort(
    (prima, seconda) =>
      prima.indice - seconda.indice ||
      seconda.normalizzata.length -
        prima.normalizzata.length
  );

  return trovate[0]?.nome || "Bologna";
}

function hashTesto(testo) {
  let hash = 0;
  const valore = String(testo || "");

  for (let indice = 0; indice < valore.length; indice += 1) {
    hash =
      (hash * 31 + valore.charCodeAt(indice)) >>> 0;
  }

  return hash;
}

export function scegliTemaSpotted(testo, seed = "") {
  const testoNormalizzato = normalizzaTesto(testo);
  const temaPredefinito = TEMI[TEMI.length - 1];
  let temaScelto = temaPredefinito;
  let punteggioMigliore = 0;

  TEMI.forEach((tema) => {
    if (tema.parole.length === 0) return;

    const punteggio = tema.parole.reduce(
      (totale, parola) => {
        const regex = new RegExp(
          `\\b${escapeRegExp(
            normalizzaTesto(parola)
          )}\\b`,
          "i"
        );

        return totale + (regex.test(testoNormalizzato) ? 1 : 0);
      },
      0
    );

    if (punteggio > punteggioMigliore) {
      temaScelto = tema;
      punteggioMigliore = punteggio;
    }
  });

  const localita = trovaLocalita(testoNormalizzato);
  const tags = [localita, temaScelto.etichetta].filter(
    (tag, indice, elenco) =>
      tag && elenco.indexOf(tag) === indice
  );

  const fileScelto =
    temaScelto.files[
      hashTesto(`${testoNormalizzato}|${seed}`) %
        temaScelto.files.length
    ];

  return {
    ...temaScelto,
    file: fileScelto,
    localita,
    tags
  };
}
